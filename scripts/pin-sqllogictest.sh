#!/usr/bin/env bash
# Writes sqllogictest/manifest-full.txt: every test file in SQLite's
# sqllogictest repository at one check-in, with its SHA-256.
#
#   scripts/pin-sqllogictest.sh <checkin-hash>
#
# Run it only to move the full corpus to a new check-in. The chain of trust:
# Fossil names a check-in by the SHA-1 of its manifest, and that manifest lists
# the SHA-1 of every file. Both are checked before any SHA-256 is written, so
# the pinned list matches upstream exactly. Files land in sqllogictest/test/.
set -euo pipefail

checkin="${1:?usage: scripts/pin-sqllogictest.sh <checkin-hash>}"
root="$(cd "$(dirname "$0")/.." && pwd)"
source_url="https://www.sqlite.org/sqllogictest"
out="$root/sqllogictest/manifest-full.txt"
"$root/scripts/fetch-sqllogictest.sh" --setup-only
dest="$root/sqllogictest/test"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
curl -sSfL "$source_url/raw/$checkin" -o "$work/checkin"
actual="$(shasum -a 1 "$work/checkin" | cut -d' ' -f1)"
if [ "$actual" != "$checkin" ]; then
  echo "check-in manifest hashes to $actual, not $checkin" >&2
  exit 1
fi
date="$(sed -n 's/^D //p' "$work/checkin")"

# "F test/<path> <sha1>" lines, test files only.
sed -n 's#^F test/\([^ ]*\.test\) \([0-9a-f]*\).*#\2  \1#p' "$work/checkin" | sort -k2 > "$work/sha1"
echo "$(wc -l < "$work/sha1" | tr -d ' ') test files at $checkin ($date)"

fetch() {
  local sha="$1" path="$2" target="$dest/$2"
  if [ -f "$target" ] && [ "$(shasum -a 1 "$target" | cut -d' ' -f1)" = "$sha" ]; then
    return
  fi
  mkdir -p "$(dirname "$target")"
  curl -sSfL --retry 3 "$source_url/raw/test/$path?ci=$checkin" -o "$target.part"
  mv "$target.part" "$target"
}
export -f fetch
export dest source_url checkin
# Four downloads at a time is quick and polite to sqlite.org.
xargs -P 4 -n 2 bash -c 'fetch "$0" "$1"' < "$work/sha1"

(cd "$dest" && shasum -a 1 -c --quiet "$work/sha1")

{
  echo "# The full SQLite sqllogictest suite: every test file at one check-in."
  echo "# Generated by scripts/pin-sqllogictest.sh from Fossil's own SHA-1 list."
  echo "# Fetch with scripts/fetch-sqllogictest.sh --full. Paths are relative to test/ upstream."
  echo "# corpus: full suite"
  echo "# source: $source_url"
  echo "# checkin: $checkin"
  (cd "$dest" && awk '{print $2}' "$work/sha1" | xargs shasum -a 256)
} > "$out"
echo "wrote $out"
