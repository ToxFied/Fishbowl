//! Turns per-file results into the published report.
//!
//! The report holds no timings or machine details, so the same engine and
//! corpus always produce the same bytes. A change in the committed report is
//! then always a real change in behavior.

use std::collections::BTreeMap;
use std::fmt::Write;

use serde::Serialize;

use crate::{Counts, FileResult};

#[derive(Debug, Serialize)]
pub struct Report {
    pub corpus: CorpusInfo,
    pub totals: Totals,
    pub files: Vec<FileSummary>,
    pub failure_reasons: Vec<ReasonSummary>,
}

#[derive(Debug, Serialize)]
pub struct CorpusInfo {
    /// The manifest's `# corpus:` line, such as "full suite".
    pub name: String,
    pub source: String,
    pub checkin: String,
    pub files: usize,
    /// False when files were passed on the command line instead of the
    /// verified manifest. Such a run is for debugging, not for quoting.
    pub pinned: bool,
}

#[derive(Debug, Serialize)]
pub struct Totals {
    pub records: Counts,
    pub statements: Counts,
    pub queries: Counts,
    pub skipped: u64,
    /// Passed records over records run, as a percentage.
    pub pass_rate: f64,
    pub query_pass_rate: f64,
}

#[derive(Debug, Serialize)]
pub struct FileSummary {
    #[serde(flatten)]
    pub result: FileResult,
    pub pass_rate: f64,
}

#[derive(Debug, Serialize)]
pub struct ReasonSummary {
    pub reason: String,
    pub count: u64,
    /// The first failure with this reason, in file order.
    pub example: String,
}

pub fn percent(counts: Counts) -> f64 {
    if counts.total() == 0 {
        return 0.0;
    }
    // Two decimals, rounded down so the report never overstates.
    (counts.passed as f64 * 10_000.0 / counts.total() as f64).floor() / 100.0
}

pub fn build(corpus: CorpusInfo, mut files: Vec<FileResult>) -> Report {
    files.sort_by(|a, b| a.path.cmp(&b.path));
    let mut statements = Counts::default();
    let mut queries = Counts::default();
    let mut skipped = 0;
    let mut reasons: BTreeMap<String, (u64, String)> = BTreeMap::new();
    for file in &files {
        statements.add(file.statements);
        queries.add(file.queries);
        skipped += file.skipped;
        for failure in &file.failures {
            let entry = reasons.entry(failure.reason.clone()).or_insert_with(|| {
                (
                    0,
                    format!("{}:{}: {}", file.path, failure.line, failure.message),
                )
            });
            entry.0 += 1;
        }
    }
    let mut records = statements;
    records.add(queries);

    let mut failure_reasons: Vec<ReasonSummary> = reasons
        .into_iter()
        .map(|(reason, (count, example))| ReasonSummary {
            reason,
            count,
            example,
        })
        .collect();
    failure_reasons.sort_by(|a, b| b.count.cmp(&a.count).then(a.reason.cmp(&b.reason)));

    Report {
        corpus,
        totals: Totals {
            records,
            statements,
            queries,
            skipped,
            pass_rate: percent(records),
            query_pass_rate: percent(queries),
        },
        files: files
            .into_iter()
            .map(|result| FileSummary {
                pass_rate: percent(result.records()),
                result,
            })
            .collect(),
        failure_reasons,
    }
}

pub fn markdown(report: &Report) -> String {
    let t = &report.totals;
    let mut out = String::new();
    let _ = writeln!(out, "# sqllogictest results: {}\n", report.corpus.name);
    let _ = writeln!(
        out,
        "Generated by `fishbowl-slt`. Do not edit by hand. See [the harness notes](../docs/sqllogictest.md).\n"
    );
    if !report.corpus.pinned {
        let _ = writeln!(
            out,
            "**Unpinned run: these files were not checked against the manifest.**\n"
        );
    }
    let _ = writeln!(
        out,
        "**{:.2}%** of records pass ({} of {}). Queries alone: **{:.2}%** ({} of {}).\n",
        t.pass_rate,
        t.records.passed,
        t.records.total(),
        t.query_pass_rate,
        t.queries.passed,
        t.queries.total()
    );
    let _ = writeln!(
        out,
        "Corpus: {} files from [{}]({}) at check-in `{}`. {} records were skipped because the file marks them as not applying to SQLite.\n",
        report.corpus.files,
        report.corpus.source,
        report.corpus.source,
        report.corpus.checkin,
        t.skipped
    );
    let _ = writeln!(out, "| | Passed | Failed | Pass rate |");
    let _ = writeln!(out, "| --- | ---: | ---: | ---: |");
    for (label, counts) in [
        ("Statements", t.statements),
        ("Queries", t.queries),
        ("All records", t.records),
    ] {
        let _ = writeln!(
            out,
            "| {label} | {} | {} | {:.2}% |",
            counts.passed,
            counts.failed,
            percent(counts)
        );
    }

    let _ = writeln!(out, "\n## Top failure reasons\n");
    let _ = writeln!(out, "| Count | Reason | First example |");
    let _ = writeln!(out, "| ---: | --- | --- |");
    for reason in report.failure_reasons.iter().take(20) {
        let example: String = reason.example.chars().take(140).collect();
        let _ = writeln!(
            out,
            "| {} | {} | `{}` |",
            reason.count,
            reason.reason.replace('|', "\\|"),
            example.replace('`', "'").replace('|', "\\|")
        );
    }

    let _ = writeln!(out, "\n## By file\n");
    let _ = writeln!(out, "| File | Statements | Queries | Skipped | Pass rate |");
    let _ = writeln!(out, "| --- | ---: | ---: | ---: | ---: |");
    for file in &report.files {
        let r = &file.result;
        let _ = writeln!(
            out,
            "| `{}` | {}/{} | {}/{} | {} | {:.2}% |",
            r.path,
            r.statements.passed,
            r.statements.total(),
            r.queries.passed,
            r.queries.total(),
            r.skipped,
            file.pass_rate
        );
    }
    out
}
